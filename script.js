        let currentQuestionIndex = 0;
        let score = 0;
        let playerName = "";
        let isAnswered = false;
        let previousScreen = 'screen-welcome';
        let enteredPassword = "";
        const CORRECT_PASSWORD = "12341234";

        function switchScreen(screenId) {
            ['screen-welcome', 'screen-name', 'screen-quiz', 'screen-end', 'screen-password', 'screen-leaderboard'].forEach(id => {
                document.getElementById(id).classList.add('hidden');
            });
            document.getElementById(screenId).classList.remove('hidden');
        }

        function promptLeaderboardPassword() {
            if(!document.getElementById('screen-welcome').classList.contains('hidden')) previousScreen = 'screen-welcome';
            else if(!document.getElementById('screen-end').classList.contains('hidden')) previousScreen = 'screen-end';

            enteredPassword = "";
            updatePasswordDisplay();
            hidePasswordError();
            switchScreen('screen-password');
        }

        function closePasswordModal() {
            switchScreen(previousScreen);
        }

        function pressNumpad(num) {
            if (enteredPassword.length < 12) {
                enteredPassword += num;
                updatePasswordDisplay();
                hidePasswordError();
                if (enteredPassword === CORRECT_PASSWORD) {
                    setTimeout(() => submitPassword(), 150);
                }
            }
        }

        function clearNumpad() {
            enteredPassword = "";
            updatePasswordDisplay();
            hidePasswordError();
        }

        function backspaceNumpad() {
            enteredPassword = enteredPassword.slice(0, -1);
            updatePasswordDisplay();
            hidePasswordError();
        }

        function updatePasswordDisplay() {
            const dotsEl = document.getElementById('pass-dots');
            if (enteredPassword.length === 0) {
                dotsEl.innerText = "••••••••";
                dotsEl.className = "tracking-widest font-mono text-2xl text-slate-600 h-8 flex items-center justify-center";
            } else {
                dotsEl.innerText = "•".repeat(enteredPassword.length);
                dotsEl.className = "tracking-widest font-mono text-2xl text-amber-400 h-8 flex items-center justify-center";
            }
        }

        function hidePasswordError() {
            const err = document.getElementById('pass-error');
            err.classList.add('opacity-0');
        }

        function showPasswordError() {
            const err = document.getElementById('pass-error');
            err.classList.remove('opacity-0');
            const box = document.getElementById('pass-display-box');
            box.classList.add('animate-shake', 'border-rose-500');
            setTimeout(() => box.classList.remove('animate-shake', 'border-rose-500'), 400);
        }

        function submitPassword() {
            if (enteredPassword === CORRECT_PASSWORD) {
                renderLeaderboardList();
                switchScreen('screen-leaderboard');
            } else {
                showPasswordError();
            }
        }

        function goToNameScreen() {
            switchScreen('screen-name');
            setTimeout(() => document.getElementById('player-name-input').focus(), 100);
        }

        function goBackToWelcome() {
            switchScreen('screen-welcome');
        }

        function openLeaderboard() {
            if(!document.getElementById('screen-welcome').classList.contains('hidden')) previousScreen = 'screen-welcome';
            else if(!document.getElementById('screen-end').classList.contains('hidden')) previousScreen = 'screen-end';
            else previousScreen = 'screen-welcome';
            
            renderLeaderboardList();
            switchScreen('screen-leaderboard');
        }

        function closeLeaderboard() {
            switchScreen(previousScreen);
        }

        function startQuiz() {
            const input = document.getElementById('player-name-input');
            const errorEl = document.getElementById('name-error');
            playerName = input.value.trim();

            if(!playerName) {
                errorEl.classList.remove('hidden');
                input.classList.add('border-rose-500');
                input.classList.add('animate-shake');
                setTimeout(() => input.classList.remove('animate-shake'), 400);
                return;
            }
            errorEl.classList.add('hidden');
            input.classList.remove('border-rose-500');

            currentQuestionIndex = 0;
            score = 0;
            switchScreen('screen-quiz');
            loadQuestion();
        }

        function loadQuestion() {
            isAnswered = false;
            document.getElementById('next-btn-container').classList.add('hidden');

            const q = questionsData[currentQuestionIndex];
            document.getElementById('current-q-num').innerText = currentQuestionIndex + 1;
            document.getElementById('total-q-num').innerText = questionsData.length;
            document.getElementById('current-score-display').innerText = `النقاط: ${score}`;
            document.getElementById('quiz-category-badge').innerText = q.category;
            document.getElementById('question-text').innerText = q.question;

            const optionsContainer = document.getElementById('options-container');
            optionsContainer.innerHTML = '';

            const arabicLetters = ['أ', 'ب', 'ج', 'د'];

            q.options.forEach((opt, idx) => {
                const btn = document.createElement('button');
                btn.className = `w-full text-right p-3.5 sm:p-4 rounded-2xl bg-slate-900 border border-slate-800 hover:border-emerald-500/50 hover:bg-slate-800 text-white font-semibold text-sm sm:text-base transition-all flex items-center gap-3 group cursor-pointer shadow-sm`;
                btn.onclick = () => selectOption(idx);
                
                const badge = document.createElement('span');
                badge.className = `w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-slate-800 text-emerald-400 flex items-center justify-center font-bold text-xs shrink-0 group-hover:bg-emerald-500 group-hover:text-white transition`;
                badge.innerText = arabicLetters[idx];

                const textSpan = document.createElement('span');
                textSpan.className = 'flex-1 leading-snug';
                textSpan.innerText = opt;

                btn.appendChild(badge);
                btn.appendChild(textSpan);
                optionsContainer.appendChild(btn);
            });
        }

        function selectOption(selectedIndex) {
            if (isAnswered) return;
            isAnswered = true;

            const q = questionsData[currentQuestionIndex];
            const buttons = document.getElementById('options-container').children;

            if (selectedIndex === q.correct) {
                score++;
                buttons[selectedIndex].className = `w-full text-right p-3.5 sm:p-4 rounded-2xl bg-emerald-950/90 border-2 border-emerald-500 text-white font-semibold text-sm sm:text-base flex items-center gap-3 transition-all`;
                buttons[selectedIndex].querySelector('span').classList.add('bg-emerald-500', 'text-white');
                
                confetti({
                    particleCount: 45,
                    spread: 70,
                    origin: { y: 0.6 }
                });
            } else {
                buttons[selectedIndex].className = `w-full text-right p-3.5 sm:p-4 rounded-2xl bg-rose-950/90 border-2 border-rose-500 text-white font-semibold text-sm sm:text-base flex items-center gap-3 transition-all animate-shake`;
                buttons[selectedIndex].querySelector('span').classList.add('bg-rose-500', 'text-white');

                buttons[q.correct].className = `w-full text-right p-3.5 sm:p-4 rounded-2xl bg-emerald-950/90 border-2 border-emerald-500 text-white font-semibold text-sm sm:text-base flex items-center gap-3 transition-all`;
                buttons[q.correct].querySelector('span').classList.add('bg-emerald-500', 'text-white');
            }

            for (let btn of buttons) {
                btn.style.pointerEvents = 'none';
            }

            document.getElementById('next-btn-container').classList.remove('hidden');
        }

        function nextQuestion() {
            currentQuestionIndex++;
            if (currentQuestionIndex < questionsData.length) {
                loadQuestion();
            } else {
                finishQuiz();
            }
        }

        function finishQuiz() {
            switchScreen('screen-end');
            document.getElementById('end-player-name').innerText = playerName;
            document.getElementById('final-score-text').innerText = `${score} / ${questionsData.length}`;

            saveScoreToLeaderboard(playerName, `${score}/${questionsData.length}`);

            confetti({
                particleCount: 160,
                spread: 100,
                origin: { y: 0.5 }
            });
        }

        function restartQuiz() {
            switchScreen('screen-welcome');
            document.getElementById('player-name-input').value = '';
        }

        function saveScoreToLeaderboard(name, scoreStr) {
            let leaderboard = JSON.parse(localStorage.getItem('shatby_leaderboard') || '[]');
            const numericScore = parseInt(scoreStr.split('/')[0]);

            leaderboard.push({
                name: name,
                scoreText: scoreStr,
                numericScore: numericScore,
                date: new Date().toLocaleDateString('ar-SA')
            });

            leaderboard.sort((a, b) => b.numericScore - a.numericScore);

            if(leaderboard.length > 25) {
                leaderboard = leaderboard.slice(0, 25);
            }

            localStorage.setItem('shatby_leaderboard', JSON.stringify(leaderboard));
        }

        function renderLeaderboardList() {
            const listEl = document.getElementById('leaderboard-list');
            let leaderboard = JSON.parse(localStorage.getItem('shatby_leaderboard') || '[]');

            listEl.innerHTML = '';

            if (leaderboard.length === 0) {
                listEl.innerHTML = `
                    <div class="text-center py-12 text-slate-400 text-sm">
                        <i class="fa-solid fa-medal text-4xl mb-3 text-slate-600 block"></i>
                        لا توجد نتائج مسجلة حتى الآن. كن أول المشاركين!
                    </div>
                `;
                return;
            }

            leaderboard.forEach((item, index) => {
                const itemDiv = document.createElement('div');
                itemDiv.className = `flex items-center justify-between p-3.5 rounded-2xl bg-slate-900 border ${index === 0 ? 'border-amber-500/60 bg-amber-500/5' : 'border-slate-800'} shadow-sm`;

                let rankBadge = `<span class="w-7 h-7 rounded-xl bg-slate-800 text-slate-300 font-bold text-xs flex items-center justify-center">${index + 1}</span>`;
                if(index === 0) rankBadge = `<span class="w-7 h-7 rounded-xl bg-amber-500 text-slate-950 font-black text-xs flex items-center justify-center shadow"><i class="fa-solid fa-crown text-xs"></i></span>`;
                if(index === 1) rankBadge = `<span class="w-7 h-7 rounded-xl bg-slate-300 text-slate-950 font-black text-xs flex items-center justify-center">2</span>`;
                if(index === 2) rankBadge = `<span class="w-7 h-7 rounded-xl bg-amber-700 text-white font-black text-xs flex items-center justify-center">3</span>`;

                // Requested format: ( hamza mohammed : 17/20 )
                itemDiv.innerHTML = `
                    <div class="flex items-center gap-3">
                        ${rankBadge}
                        <span class="font-bold text-sm text-white">(${item.name} : ${item.scoreText})</span>
                    </div>
                    <span class="text-xs text-slate-400 font-medium">${item.date}</span>
                `;
                listEl.appendChild(itemDiv);
            });
        } 

        function clearLeaderboard() {
            if (!window.confirm('هل أنت متأكد من حذف جميع النتائج المسجلة؟')) return;

            localStorage.removeItem('shatby_leaderboard');
            renderLeaderboardList();
        }
